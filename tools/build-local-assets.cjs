// Rebuild after changing the textures or the stop model.
// Explicit allowlist: excluded music and artwork must never enter this bundle.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const resources = {
  'assets/images/estrada.jpg': 'image/jpeg',
  'assets/images/relva.jpg': 'image/jpeg',
  'assets/images/stop.svg': 'image/svg+xml',
  'assets/models/stopsign.fbx': 'application/octet-stream'
};
const embedded = {};
for (const [file, mime] of Object.entries(resources)) {
  embedded[file] = 'data:' + mime + ';base64,' + fs.readFileSync(path.join(root, file)).toString('base64');
}
const output = '// Generated by node tools/build-local-assets.cjs. Do not edit manually.\n' +
  'var recursosIncorporados = ' + JSON.stringify(embedded, null, 2) + ';\n' +
  'function recursoJogo(caminho) {\n' +
  '  var chave = caminho.replace(/^\\.\\//, "");\n' +
  '  return window.location.protocol === "file:" && recursosIncorporados[chave] || caminho;\n' +
  '}\n';
fs.writeFileSync(path.join(root, 'assets', 'embedded.js'), output);
console.log('Local assets rebuilt (' + Object.keys(embedded).length + ' files).');
